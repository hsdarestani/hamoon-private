'use strict';
const fs = require('fs');
function assert(ok, msg){ if(!ok){ console.error('FAIL:', msg); process.exitCode=1; } else console.log('OK:', msg); }
const files = ['server.js','dashboard-api.js','db.js','public/dashboard/index.html','public/dashboard/app.js','public/dashboard/styles.css'];
files.forEach(f=>assert(fs.existsSync(f), `${f} exists`));
const server = fs.readFileSync('server.js','utf8');
const api = fs.readFileSync('dashboard-api.js','utf8');
const db = fs.readFileSync('db.js','utf8');
const appJs = fs.readFileSync('public/dashboard/app.js','utf8');
const front = appJs + fs.readFileSync('public/dashboard/index.html','utf8') + fs.readFileSync('public/dashboard/styles.css','utf8');
assert(server.includes('/health'), '/health route exists');
assert(server.includes("'/dashboard/api'") || server.includes('"/dashboard/api"'), '/dashboard api mounted');
assert(server.includes('/dashboard') && server.includes('sendFile'), '/dashboard route exists');
assert(api.includes("router.post('/login'") || api.includes('router.post("/login"'), '/dashboard/api/login exists');
assert(api.includes('requireAuth') && api.includes('router.use(requireAuth'), 'dashboard auth exists');
assert(!/DASHBOARD_PASSWORD|SECRET_KEY|SERVER_SECRET_KEY|API_KEY|TOKEN/i.test(appJs), 'no frontend secret names');
assert(!/Math\.random|sampleData|demoData|mock|placeholder statistics|hardcoded chart arrays/i.test(appJs), 'no generated or sample dashboard data');
['refresh','suspend','resume','delete','check-ssh','reset-password','set-password','reveal-password'].forEach(a=>assert(api.includes(`/servers/:serverId/${a}`), `server action endpoint ${a} exists`));
assert(api.includes('/servers/:serverId/update-purchase-status'), 'purchase status server endpoint exists');
assert(api.includes('/servers/attach-afra'), 'attach Afra endpoint exists');
assert(db.includes('adminAuditLog') && api.includes('audit(req'), 'audit log helper and calls exist');
['/charts/revenue','/charts/purchases','/charts/servers-by-datacenter','/charts/wallet-flow'].forEach(p=>assert(api.includes(p), `real chart endpoint ${p} exists`));
assert(/Vazirmatn,IRANSans,Shabnam,Tahoma,Arial/.test(front), 'Persian font CSS is configured');
assert(!/console\.log\([^\n]*(password|secret|token|SERVER_SECRET_KEY|API_KEY)/i.test(api + server + db), 'no obvious password/token/server secret logging');
process.exit(process.exitCode || 0);
